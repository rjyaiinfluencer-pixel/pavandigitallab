const LOCAL_STORAGE_KEY = 'pavan_digital_lab_projects_v2';

export function getStoredProjects(): ProjectItem[] {
  if (typeof window === 'undefined') return INITIAL_PROJECTS;
  try {
    const data = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!data) return INITIAL_PROJECTS;
    const parsed = JSON.parse(data);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
  } catch (e) {
    console.error('Failed to read projects from localStorage', e);
  }
  return INITIAL_PROJECTS;
}

export function saveStoredProjects(projects: ProjectItem[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(projects));
  } catch (e) {
    console.error('Failed to save projects to localStorage', e);
  }
}

export function resetToDefaultProjects(): ProjectItem[] {
  if (typeof window !== 'undefined') {
    localStorage.removeItem(LOCAL_STORAGE_KEY);
  }
  return INITIAL_PROJECTS;
}
